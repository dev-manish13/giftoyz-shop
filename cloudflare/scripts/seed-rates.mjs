import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const NCM_NAMES = {
  BAGLUNG: "BAGLUNG BAZAR",
  "CHAINPUR SANKHUWASABHA": "CHAINPUR SANKHUWASAB",
  CHAKARGHATTI: "CHAKARGHATTI SUNSARI",
  CHITWAN: "NARAYANGHAT",
  DARBANG: "DARBANG MYAGDI",
  "DIPAYAL SILGADHI": "DIPAYAL",
  GAUSHALA: "GAUSHALA MAHOTTARI",
  GORKHA: "GORKHA BAZAR",
  HANUMANNAGAR: "HANUMANNAGR",
  ILAM: "ILAM BAZAR",
  JUGEDA: "JUGEDI",
  "MAHARAJGUNJ KAPILBASTU": "MAHARAJGUNJ KAPILBAS",
  MANGALBARE: "MANGALBARE ILAM",
  NARAYANPUR: "NARAYANPUR DANG",
  "NEPALTAR BAZAR": "NEPALTAR ILAM",
  "NEPALTAR KATHMANDU": "KAVRESTHALI",
  PALPA: "TANSEN",
  RAMPUR: "RAMPUR PALPA",
  "SAKUWA MAHENDRANAGAR": "DHANUSA MAHENDRANAGR",
  TAPLEJUNG: "PHUNGLING",
};

const dataJs = readFileSync(resolve(import.meta.dirname, "../../data.js"), "utf8");
const block = /const ncmRows = `([^`]*)`/s.exec(dataJs)?.[1];
if (!block) throw new Error("No NCM rate card in data.js");
const q = (s) => `'${s.replace(/'/g, "''")}'`;
const lines = ["-- Generated by scripts/seed-rates.mjs from data.js. Starting rate card; NCM refresh overwrites prices."];
let count = 0;
for (const line of block.split("\n")) {
  const m = /^([A-Z0-9][A-Z0-9 .()/&-]*)\|(\d+)\|(\d+)$/.exec(line.trim());
  if (!m) continue;
  const [, key, home, branch] = m;
  const ncm = NCM_NAMES[key];
  lines.push(`INSERT OR IGNORE INTO rates (key, home, branch, source, updated_ts, ncm_name) VALUES (${q(key)}, ${home}, ${branch}, 'card', unixepoch(), ${ncm ? q(ncm) : "NULL"});`);
  count++;
}
writeFileSync(resolve(import.meta.dirname, "../migrations/0002_rates.sql"), lines.join("\n") + "\n");
console.log(`rates: ${count} places`);
